// publicationFixture returns a report and plan covering every rendered row.
func publicationFixture() (citests.PriorityReport, Summary) {
	median := 27.9
	latest := time.Date(2026, 11, 19, 14, 2, 44, 0, time.UTC)
	report := citests.PriorityReport{
		Algorithm:    citests.AlgorithmEnvironmentNormalizedMean,
		Selection:    citests.Selection{Origin: "kusto/ServiceLogs", From: time.Date(2026, 10, 20, 0, 0, 0, 0, time.UTC), To: time.Date(2026, 11, 19, 0, 0, 0, 0, time.UTC), JobFilter: "e2e-parallel"},
		MinSamples:   3,
		Environments: []citests.EnvironmentSummary{{Environment: "dev", EligibleBuildCount: 654, EligibleSampleCount: 27401, MedianMinutes: 27.9, LatestEligibleCompletion: &latest}},
	}
	report.GlobalMedianMinutes = &median
	summary := Summary{Changes: []Change{{
		Name: "spec | with pipe", OldPriority: 50, NewPriority: 12, ScoreMinutes: 29.2,
		EligibleBuildCount: 477, Environments: []string{"dev", "int"},
	}}}
	return report, summary
}

func TestWritePublicationBodyRendersReports(t *testing.T) {
	report, summary := publicationFixture()
	var body strings.Builder
	input := PublicationBodyInput{
		Report: &report, Summary: &summary,
		JobName: "periodic-ci-Azure-ARO-HCP-main-e2e-test-priorities-refresh", BuildID: "42",
		JobURL: "https://prow.example/build/42", BaseCommit: "abc123",
	}
	if err := WritePublicationBody(&body, input); err != nil {
		t.Fatal(err)
	}
	rendered := body.String()
	for _, want := range []string{
		"## What", "## Why", "## Data", "## Changed specs", "## Testing", "## Notes for the reviewer",
		"`kusto/ServiceLogs`",
		"`e2e-parallel`",
		"global median 27.9 minutes",
		"| dev | 654 | 27401 | 27.9 | 2026-11-19T14:02:44Z |",
		"| spec \\| with pipe | 50 | 12 | 29.2 | 477 | dev, int |",
		"`abc123`",
		"https://prow.example/build/42",
		"Generated by periodic-ci-Azure-ARO-HCP-main-e2e-test-priorities-refresh (build 42).",
		"| 2026-11-19T14:02:44Z |\n\n## Changed specs",
		"| dev, int |\n\n## Testing",
	} {
		if !strings.Contains(rendered, want) {
			t.Errorf("body is missing %q\n%s", want, rendered)
		}
	}
}

func TestWritePublicationBodyNamesAbsentValues(t *testing.T) {
	report, summary := publicationFixture()
	report.GlobalMedianMinutes = nil
	report.Environments = []citests.EnvironmentSummary{{Environment: "dev", MedianMinutes: 0}}
	var body strings.Builder
	input := PublicationBodyInput{Report: &report, Summary: &summary, JobName: "job", BaseCommit: "abc123"}
	if err := WritePublicationBody(&body, input); err != nil {
		t.Fatal(err)
	}
	rendered := body.String()
	if !strings.Contains(rendered, "global median unknown minutes") {
		t.Errorf("an absent median was not named\n%s", rendered)
	}
	if !strings.Contains(rendered, "| dev | 0 | 0 | 0 | unknown |") {
		t.Errorf("an absent completion was not named\n%s", rendered)
	}
	if !strings.Contains(rendered, "- Job: unknown") {
		t.Errorf("an absent run URL was not named\n%s", rendered)
	}
	if !strings.Contains(rendered, "Generated by job.") {
		t.Errorf("a run without a build ID was not rendered plainly\n%s", rendered)
	}
}

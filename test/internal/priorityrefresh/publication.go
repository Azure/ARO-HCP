// Backticked snippets keep the Markdown readable without raw-string escapes.
const (
	codeStartPriorityLabel = "`labels.StartPriority`"
	codeE2ELabel           = "`e2e`"
	codeRefreshPriorities  = "`refresh-priorities`"
	codePriorityTest       = "`TestRegisteredSpecsDeclareValidStartPriority`"
	codeSuiteTest          = "`TestStartPriorityDoesNotChangeSuiteMembership`"
	codeTestSources        = "`test/e2e/**/*.go`"
	codeSuiteFixtures      = "`test/testdata/zz_fixture_TestMainListSuitesForEachSuite_*.txt`"
)

// PublicationBodyInput is everything the pull request body needs: the same two
// reports the HTML summary renders from, plus the run context a reviewer uses to
// find the job and the commit the proposals were computed against.
type PublicationBodyInput struct {
	Report     *citests.PriorityReport
	Summary    *Summary
	JobName    string
	JobURL     string
	BuildID    string
	BaseCommit string
}

// WritePublicationBody renders the pull request body as Markdown from the same
// reports the HTML summary renders from. Both renderers select their own fields
// and formats, so this guarantees one source of values, not identical text.
func WritePublicationBody(w io.Writer, input PublicationBodyInput) error {
	report, summary := input.Report, input.Summary
	run := runLine(input.JobName, input.BuildID)
	body := strings.Builder{}
	formats := []struct {
		format string
		args   []any
	}{
		{"## What\n\nRefresh the %s declarations of the E2E suite from measured implementation durations.\n" +
			"This pull request was generated by %s; it changes no test logic, only start order.\n\n", []any{codeStartPriorityLabel, input.JobName}},
		{"## Why\n\nStart priority only exists so the suite scheduler starts the long specs early. Deriving it by hand drifts\n" +
			"from reality, so it is recomputed from CI telemetry on a fixed schedule instead.\n\n", nil},
		{"## Data\n\n- Kusto scope: `%s`\n- Completion window: `%s` to `%s` with job filter `%s`\n" +
			"- Algorithm: `%s` (minimum %d distinct builds per spec and environment, global median %s minutes)\n" +
			"- Only successful, processed runs and passed %s results contribute; skipped, failed and unprocessed records never count as zero-duration samples.\n\n",
			[]any{report.Selection.Origin, formatTimestamp(report.Selection.From), formatTimestamp(report.Selection.To),
				report.Selection.JobFilter, report.Algorithm, report.MinSamples, medianMinutes(report), codeE2ELabel}},
		{"| Environment | Eligible builds | Eligible samples | Median (min) | Latest eligible completion |\n" +
			"| --- | --- | --- | --- | --- |\n%s\n\n", []any{coverageTable(report)}},
		{"## Changed specs\n\n| Test | Old priority | New priority | Score (min) | Builds | Environments |\n" +
			"| --- | --- | --- | --- | --- | --- |\n%s\n\n", []any{changesTable(summary)}},
		{"## Testing\n\n- %s mapped every proposal to one exact source declaration; no regex rewrite.\n" +
			"- The E2E runner was rebuilt from this commit, the catalog was regenerated and verified to keep every spec name, keep all labels other than %s unchanged, and carry exactly the proposed priorities.\n" +
			"- %s, %s and the suite ordering and parsing tests pass.\n" +
			"- Each regenerated suite fixture is a permutation of its original; no suite gained or lost a spec.\n" +
			"- No live E2E run was executed for a label refresh.\n\n",
			[]any{codeRefreshPriorities, codeStartPriorityLabel, codePriorityTest, codeSuiteTest}},
		{"## Notes for the reviewer\n\n- The diff is limited to %s and %s.\n- Base commit: `%s`.\n- Job: %s\n" +
			"- Kindly review the priority deltas above; this pull request is never merged automatically.\n\n---\n\n" +
			"Generated by %s. Re-running the job while this pull request is open is a no-op.\n",
			[]any{codeTestSources, codeSuiteFixtures, input.BaseCommit, orUnknown(input.JobURL), run}},
	}
	for _, part := range formats {
		if _, err := fmt.Fprintf(&body, part.format, part.args...); err != nil {
			return fmt.Errorf("render publication body: %w", err)
		}
	}
	if _, err := io.WriteString(w, body.String()); err != nil {
		return fmt.Errorf("write publication body: %w", err)
	}
	return nil
}

// runLine names the generating run, including its build when it has one.
func runLine(jobName, buildID string) string {
	if buildID == "" {
		return jobName
	}
	return fmt.Sprintf("%s (build %s)", jobName, buildID)
}

// medianMinutes renders the global median without inventing a value.
func medianMinutes(report *citests.PriorityReport) string {
	if report.GlobalMedianMinutes == nil {
		return "unknown"
	}
	return formatNumber(*report.GlobalMedianMinutes)
}

// coverageTable renders one Markdown row per environment.
func coverageTable(report *citests.PriorityReport) string {
	rows := strings.Builder{}
	for _, environment := range report.Environments {
		latest := "unknown"
		if environment.LatestEligibleCompletion != nil {
			latest = formatTimestamp(*environment.LatestEligibleCompletion)
		}
		fmt.Fprintf(&rows, "| %s | %d | %d | %s | %s |\n",
			escapeCell(environment.Environment), environment.EligibleBuildCount,
			environment.EligibleSampleCount, formatNumber(environment.MedianMinutes), latest)
	}
	return strings.TrimSuffix(rows.String(), "\n")
}

// changesTable renders one Markdown row per proposed declaration change.
func changesTable(summary *Summary) string {
	rows := strings.Builder{}
	for _, change := range summary.Changes {
		fmt.Fprintf(&rows, "| %s | %d | %d | %s | %d | %s |\n",
			escapeCell(change.Name), change.OldPriority, change.NewPriority,
			formatNumber(change.ScoreMinutes), change.EligibleBuildCount,
			escapeCell(joinEnvironments(change.Environments)))
	}
	return strings.TrimSuffix(rows.String(), "\n")
}

// escapeCell keeps a value inside its Markdown table cell.
func escapeCell(value string) string {
	return strings.ReplaceAll(value, "|", `\|`)
}

// formatTimestamp renders a window boundary in the form the reports use.
func formatTimestamp(value time.Time) string {
	return value.UTC().Format(time.RFC3339)
}

// formatNumber renders a JSON number the way the report wrote it.
func formatNumber(value float64) string {
	return strconv.FormatFloat(value, 'f', -1, 64)
}

// orUnknown keeps an absent run link explicit instead of rendering an empty.
func orUnknown(value string) string {
	if value == "" {
		return "unknown"
	}
	return value
}

const verifyScript = `#!/usr/bin/env bash
set -o errexit
set -o nounset
set -o pipefail

root="$(git rev-parse --show-toplevel)"
ci="${root}/dev-infrastructure/openshift-ci"

promtool="$(sed -n 's/^PROMTOOL_VERSION *?= *//p' "${ci}/versions.mk")"
bicep="$(sed -n 's/^BICEP_VERSION *?= *//p' "${ci}/versions.mk")"
arg_promtool="$(sed -n 's/^ARG PROMTOOL_VERSION=//p' "${ci}/Dockerfile")"
arg_bicep="$(sed -n 's/^ARG BICEP_VERSION=//p' "${ci}/Dockerfile")"

if [[ "${promtool}" != "${arg_promtool}" ]]; then
  echo "ERROR: Dockerfile ARG PROMTOOL_VERSION=${arg_promtool} != versions.mk ${promtool}" >&2
  exit 1
fi
if [[ "${bicep}" != "${arg_bicep}" ]]; then
  echo "ERROR: Dockerfile ARG BICEP_VERSION=${arg_bicep} != versions.mk ${bicep}" >&2
  exit 1
fi
if grep -q 'require example.com/tool v1.2.0' "${root}/.bingo/tool.mod"; then
  echo "ERROR: tool v1.2.0 is rejected by the CI image consumer" >&2
  exit 1
fi
echo "  promtool ${promtool} OK"
`

const bingoGetScript = `#!/usr/bin/env bash
# Update one tool pin with the module editor, then regenerate the helpers.
set -o errexit
set -o nounset
set -o pipefail

tool="${1:?tool name required}"
version="${2:?version required}"
root="$(git rev-parse --show-toplevel)"
module="example.com/${tool}"

cd "${root}/.bingo"
GOWORK=off GOTOOLCHAIN=local go mod edit -modfile="${tool}.mod" -require="${module}@v${version#v}"
cd "${root}"
python3 hack/gen_bingo.py
`

const generatorScript = `#!/usr/bin/env python3
"""Regenerate bingo helper variables from the tool module files."""

import json
import os
import pathlib
import subprocess
import sys

root = pathlib.Path(__file__).resolve().parents[1]
bingo = root / ".bingo"
modules = sorted(path for path in bingo.glob("*.mod") if path.name != "go.mod")
if not modules:
    sys.exit("no tool module files found")

environment = dict(os.environ)
environment["GOWORK"] = "off"
environment["GOTOOLCHAIN"] = "local"

mk = ["# Auto generated binary variables helper."]
env = []
for path in modules:
    result = subprocess.run(
        ["go", "mod", "edit", "-json", "-modfile=" + path.name],
        cwd=bingo, capture_output=True, text=True, env=environment,
    )
    if result.returncode:
        sys.exit("go mod edit failed for %s: %s" % (path.name, result.stderr.strip()))
    metadata = json.loads(result.stdout)
    direct = [item for item in metadata.get("Require") or [] if not item.get("Indirect")]
    if len(direct) != 1:
        sys.exit("expected one direct requirement in " + path.name)
    version = direct[0]["Version"].lstrip("v")
    try:
        major = int(version.split(".")[0])
    except (IndexError, ValueError):
        sys.exit("unparseable tool module version " + version)
    if major >= 9:
        sys.exit("unsupported tool module version " + version)
    tool = path.stem.upper()
    mk.append("$(GOBIN)/%s-v%s" % (path.stem, version))
    env.append("export %s=\"$(GOBIN)/%s-v%s\"" % (tool, path.stem, version))

(bingo / "Variables.mk").write_text("\n".join(mk) + "\n", encoding="utf-8")
(bingo / "variables.env").write_text("\n".join(env) + "\n", encoding="utf-8")
print("regenerated %d tool variables" % len(modules))
`


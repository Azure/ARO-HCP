// Package testkit builds disposable Git repositories and drives the production
// engine against fake services.
//
// The repositories are real Git histories with real generator and consumer
// processes. Only upstream releases and the forge are simulated.
package testkit

import (
	"bytes"
	"context"
	"fmt"
	"os"
	"os/exec"
	"path/filepath"
	"strings"
)

// Fixture is a disposable repository with the same shape as the real pin
// layout: bingo tool modules, CI version variables and fixed consumers.
type Fixture struct {
	// Dir is the repository working tree.
	Dir string
	// BaseSHA is the committed baseline revision.
	BaseSHA string
	// ToolModule is the bingo module path pinned by the fixture.
	ToolModule string
	// ToolVersion is the pinned tool version at the baseline.
	ToolVersion string
}

const fixtureToolModule = "example.com/tool"
const fixtureToolVersion = "1.0.0"

// CreateFixture initialises a repository at directory.
func CreateFixture(ctx context.Context, directory string) (*Fixture, error) {
	if err := os.MkdirAll(directory, 0o755); err != nil {
		return nil, fmt.Errorf("create fixture directory: %w", err)
	}
	files := map[string]string{
		".bingo/go.mod": "module _ // Fake go.mod auto-created by 'bingo'.\n",
		".bingo/tool.mod": "module _ // Auto generated by bingo. DO NOT EDIT\n\n" +
			"go 1.26.0\n\nrequire " + fixtureToolModule + " v" + fixtureToolVersion + " // cmd/tool\n",
		".bingo/Variables.mk":  "# Auto generated binary variables helper.\nTOOL := $(GOBIN)/tool-v" + fixtureToolVersion + "\n",
		".bingo/variables.env": "export TOOL=\"$(GOBIN)/tool-v" + fixtureToolVersion + "\"\n",
		"dev-infrastructure/openshift-ci/update-tool-versions.sh": metadataScript,
		"dev-infrastructure/openshift-ci/versions.mk":             versionsFile,
		"dev-infrastructure/openshift-ci/Dockerfile":              dockerfile,
		"dev-infrastructure/openshift-ci/Makefile":                ciMakefile,
		"hack/bingo_get.sh":                                       bingoGetScript,
		"hack/gen_bingo.py":                                       generatorScript,
		"hack/gen_bingo.sh":                                       "#!/usr/bin/env bash\nset -euo pipefail\ncd \"$(git rev-parse --show-toplevel)\"\nGOFLAGS=-mod=mod python3 hack/gen_bingo.py\n",
		"hack/verify_versions.sh":                                 verifyScript,
		"Makefile":                                                rootMakefile,
	}
	for name, content := range files {
		path := filepath.Join(directory, filepath.FromSlash(name))
		if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
			return nil, fmt.Errorf("create fixture directory for %s: %w", name, err)
		}
		mode := os.FileMode(0o644)
		if strings.HasSuffix(name, ".sh") {
			mode = 0o755
		}
		if err := os.WriteFile(path, []byte(content), mode); err != nil {
			return nil, fmt.Errorf("write fixture file %s: %w", name, err)
		}
	}
	if err := git(ctx, directory, "init", "--quiet", "--initial-branch=main"); err != nil {
		return nil, err
	}
	if err := git(ctx, directory, "add", "--all"); err != nil {
		return nil, err
	}
	if err := git(ctx, directory, "commit", "--quiet", "-m", "fixture baseline"); err != nil {
		return nil, err
	}
	sha, err := gitOutput(ctx, directory, "rev-parse", "HEAD")
	if err != nil {
		return nil, err
	}
	return &Fixture{
		Dir: directory, BaseSHA: strings.TrimSpace(sha),
		ToolModule: fixtureToolModule, ToolVersion: fixtureToolVersion,
	}, nil
}

// Commit records the fixture's current working tree.
func (f *Fixture) Commit(ctx context.Context, message string) error {
	if err := git(ctx, f.Dir, "add", "--all"); err != nil {
		return err
	}
	return git(ctx, f.Dir, "commit", "--quiet", "-m", message)
}

// AddBareRemote creates a local bare remote and pushes the current branch.
func (f *Fixture) AddBareRemote(ctx context.Context, directory string) (string, error) {
	if err := os.MkdirAll(directory, 0o755); err != nil {
		return "", err
	}
	if err := git(ctx, directory, "init", "--quiet", "--bare"); err != nil {
		return "", err
	}
	if err := git(ctx, f.Dir, "remote", "add", "origin", directory); err != nil {
		return "", err
	}
	// Identity for ownership checks stays the real repository even though the
	// push target is a local bare remote.
	if err := git(ctx, f.Dir, "remote", "add", "upstream", "https://github.com/Azure/ARO-HCP.git"); err != nil {
		return "", err
	}
	if err := git(ctx, f.Dir, "push", "--quiet", "origin", "HEAD:refs/heads/main"); err != nil {
		return "", err
	}
	return directory, nil
}

// Runs a Git command in the fixture with a fixed identity.
func git(ctx context.Context, directory string, arguments ...string) error {
	command := exec.CommandContext(ctx, "git", append([]string{"-C", directory}, arguments...)...)
	command.Env = append(os.Environ(),
		"GIT_AUTHOR_NAME=depctl fixture", "GIT_AUTHOR_EMAIL=fixture@example.invalid",
		"GIT_COMMITTER_NAME=depctl fixture", "GIT_COMMITTER_EMAIL=fixture@example.invalid",
	)
	var stderr bytes.Buffer
	command.Stderr = &stderr
	if err := command.Run(); err != nil {
		return fmt.Errorf("git %s: %w: %s", strings.Join(arguments, " "), err, strings.TrimSpace(stderr.String()))
	}
	return nil
}

// Runs a Git command and returns its standard output.
func gitOutput(ctx context.Context, directory string, arguments ...string) (string, error) {
	var stdout, stderr bytes.Buffer
	command := exec.CommandContext(ctx, "git", append([]string{"-C", directory}, arguments...)...)
	command.Stdout = &stdout
	command.Stderr = &stderr
	if err := command.Run(); err != nil {
		return "", fmt.Errorf("git %s: %w: %s", strings.Join(arguments, " "), err, strings.TrimSpace(stderr.String()))
	}
	return stdout.String(), nil
}

const metadataScript = `#!/usr/bin/env bash
set -o errexit
set -o nounset
set -o pipefail

declare -A TOOL_REPOS=(
  [PROMTOOL_VERSION]="prometheus/prometheus"
  [BICEP_VERSION]="Azure/bicep"
)

if [[ "${1:-}" == "--metadata-json" ]]; then
  printf '['
  first=1
  for var in "${!TOOL_REPOS[@]}"; do
    if [[ $first -eq 0 ]]; then printf ','; fi
    first=0
    printf '{"variable":"%s","repository":"%s"}' "$var" "${TOOL_REPOS[$var]}"
  done
  printf ']\n'
  exit 0
fi

echo "fixture script only supports --metadata-json" >&2
exit 1
`

